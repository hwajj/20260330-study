/**
 * study/{track}/*.md → site/docs/{track}/ (archive 제외)
 * 사이드바: site/docs/.vitepress/study-sidebar.mts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SITE_ROOT = path.resolve(__dirname, "..");
const REPO_ROOT = path.resolve(SITE_ROOT, "..");
const STUDY_ROOT = path.join(REPO_ROOT, "study");
const DOCS_ROOT = path.join(SITE_ROOT, "docs");

const TRACKS = [
  { id: "fe", label: "FE · 커리큘럼 Day" },
  { id: "si", label: "SI" },
  { id: "agent", label: "Agent 포폴" },
  { id: "colleague", label: "Colleague 커밋" },
  { id: "tech-survey", label: "IT 훑기" },
];

function titleFromMd(content, fallback) {
  const m = content.match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : fallback;
}

/** VitePress MD는 Vue로 컴파일되어 `{{`가 템플릿으로 파싱될 수 있음 */
function sanitizeForVitePress(content) {
  return content
    .replace(/\{\{/g, "&#123;&#123;")
    .replace(/\}\}/g, "&#125;&#125;");
}

function copyTrack(trackId) {
  const srcDir = path.join(STUDY_ROOT, trackId);
  const destDir = path.join(DOCS_ROOT, trackId);

  if (!fs.existsSync(srcDir)) {
    console.warn(`skip missing track: ${trackId}`);
    return [];
  }

  fs.rmSync(destDir, { recursive: true, force: true });
  fs.mkdirSync(destDir, { recursive: true });

  const entries = fs
    .readdirSync(srcDir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(".md") && e.name !== "README.md");

  entries.sort((a, b) => a.name.localeCompare(b.name, "en"));

  const sidebarItems = [];

  for (const entry of entries) {
    const src = path.join(srcDir, entry.name);
    const dest = path.join(destDir, entry.name);
    const raw = fs.readFileSync(src, "utf8");
    fs.writeFileSync(dest, sanitizeForVitePress(raw), "utf8");
    const slug = entry.name.replace(/\.md$/, "");
    const content = fs.readFileSync(src, "utf8");
    sidebarItems.push({
      text: titleFromMd(content, slug),
      link: `/${trackId}/${slug}`,
    });
  }

  const readme = path.join(srcDir, "README.md");
  if (fs.existsSync(readme)) {
    const readmeRaw = fs.readFileSync(readme, "utf8");
    fs.writeFileSync(
      path.join(destDir, "index.md"),
      sanitizeForVitePress(readmeRaw),
      "utf8",
    );
  }

  return sidebarItems;
}

const sidebarExport = {};

for (const { id, label } of TRACKS) {
  const items = copyTrack(id);
  sidebarExport[`/${id}/`] = [
    { text: `${label} 개요`, link: `/${id}/` },
    ...items,
  ];
  console.log(`sync ${id}: ${items.length} pages`);
}

const sidebarPath = path.join(DOCS_ROOT, ".vitepress", "study-sidebar.mts");
const sidebarSource = `// generated by site/scripts/sync-study-docs.mjs — do not edit
import type { DefaultTheme } from "vitepress";

export const studySidebar: Record<string, DefaultTheme.SidebarItem[]> = ${JSON.stringify(
  sidebarExport,
  null,
  2,
)};
`;

fs.mkdirSync(path.dirname(sidebarPath), { recursive: true });
fs.writeFileSync(sidebarPath, sidebarSource, "utf8");
console.log("wrote", path.relative(REPO_ROOT, sidebarPath));
